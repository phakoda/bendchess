#!/usr/bin/env python3
"""Generate PROOF.bend, the proofs of LAWS.bend.

Finite-domain laws are proven by exhaustive case analysis: every leaf is
closed by reflexivity ({==}) after the checker evaluates the engine's
definitions on concrete values (move_encoding alone has 64*64*8 = 32,768
cases). The general laws (selection, make-move state) are proven by
structural induction over bit words and by unfolding Pos.after on an
arbitrary position.
"""
import itertools
import os

FILES = ["FA", "FB", "FC", "FD", "FE", "FF", "FG", "FH"]
RANKS = [f"R{i}" for i in range(1, 9)]
COLORS = ["White", "Black"]
PTYPES = ["Pawn", "Knight", "Bishop", "Rook", "Queen", "King"]
FLAGS = ["Quiet", "Double", "Castle", "EnPassant", "PromoN", "PromoB", "PromoR", "PromoQ"]
STEPS = ["N", "S", "E", "W", "NE", "NW", "SW", "SE", "NNE", "NNW", "NEE", "NWW", "SSW", "SSE", "SWW", "SEE"]

HEADER = '''# GENERATED by tools/gen_proofs.py -- the proofs of LAWS.bend.
# Exhaustive laws: one reflexivity leaf per case. General laws: induction
# on bit words (Word(n)) and unfolding of Pos.after on any position.

import Base
import ./src/core.bend as C
import ./src/board.bend as B
import ./LAWS.bend as Laws

# Bit-word lemmas
# ---------------
# Oriented {simpler == larger} so that `%lemma : P` rewrites the larger
# form (marked _ in P) into the simpler one.

def Word.ones(n: Nat) -> Word(n):
  match n:
    case 0n:
      WNil{}
    case 1n+p:
      WCon{True{}, Word.ones(p)}

def w.and_ones(n: Nat, w: Word(n)) -> {w == Word.and(n, w, Word.ones(n)) : Word(n)}:
  match n:
    case 0n:
      match w:
        case WNil{}:
          {==}
    case 1n+p:
      match w:
        case WCon{True{}, t}:
          %w.and_ones(p, t) : {WCon{True{}, t} == WCon{True{}, _} : Word(1n+p)}
          {==}
        case WCon{False{}, t}:
          %w.and_ones(p, t) : {WCon{False{}, t} == WCon{False{}, _} : Word(1n+p)}
          {==}

def w.and_zero(n: Nat, w: Word(n)) -> {Word.zero(n) == Word.and(n, w, Word.zero(n)) : Word(n)}:
  match n:
    case 0n:
      match w:
        case WNil{}:
          {==}
    case 1n+p:
      match w:
        case WCon{True{}, t}:
          %w.and_zero(p, t) : {WCon{False{}, Word.zero(p)} == WCon{False{}, _} : Word(1n+p)}
          {==}
        case WCon{False{}, t}:
          %w.and_zero(p, t) : {WCon{False{}, Word.zero(p)} == WCon{False{}, _} : Word(1n+p)}
          {==}

def w.or_zero(n: Nat, w: Word(n)) -> {w == Word.or(n, w, Word.zero(n)) : Word(n)}:
  match n:
    case 0n:
      match w:
        case WNil{}:
          {==}
    case 1n+p:
      match w:
        case WCon{True{}, t}:
          %w.or_zero(p, t) : {WCon{True{}, t} == WCon{True{}, _} : Word(1n+p)}
          {==}
        case WCon{False{}, t}:
          %w.or_zero(p, t) : {WCon{False{}, t} == WCon{False{}, _} : Word(1n+p)}
          {==}

def w.zero_or(n: Nat, w: Word(n)) -> {w == Word.or(n, Word.zero(n), w) : Word(n)}:
  match n:
    case 0n:
      match w:
        case WNil{}:
          {==}
    case 1n+p:
      match w:
        case WCon{True{}, t}:
          %w.zero_or(p, t) : {WCon{True{}, t} == WCon{True{}, _} : Word(1n+p)}
          {==}
        case WCon{False{}, t}:
          %w.zero_or(p, t) : {WCon{False{}, t} == WCon{False{}, _} : Word(1n+p)}
          {==}

def w.not_ones(n: Nat) -> {Word.zero(n) == Word.not(n, Word.ones(n)) : Word(n)}:
  match n:
    case 0n:
      {==}
    case 1n+p:
      %w.not_ones(p) : {WCon{False{}, Word.zero(p)} == WCon{False{}, _} : Word(1n+p)}
      {==}

def w.not_zero(n: Nat) -> {Word.ones(n) == Word.not(n, Word.zero(n)) : Word(n)}:
  match n:
    case 0n:
      {==}
    case 1n+p:
      %w.not_zero(p) : {WCon{True{}, Word.ones(p)} == WCon{True{}, _} : Word(1n+p)}
      {==}

def b.and_andnot(a: Bool, b: Bool) -> {False{} == Bool.and(Bool.and(a, b), Bool.not(a)) : Bool}:
  match a b:
    case True{} True{}:
      {==}
    case True{} False{}:
      {==}
    case False{} True{}:
      {==}
    case False{} False{}:
      {==}

def w.and_andnot(n: Nat, a: Word(n), b: Word(n)) ->
  {Word.zero(n) == Word.and(n, Word.and(n, a, b), Word.not(n, a)) : Word(n)}:
  match n:
    case 0n:
      match a b:
        case WNil{} WNil{}:
          {==}
    case 1n+p:
      match a b:
        case WCon{ab, at} WCon{bb, bt}:
          -x = Bool.and(Bool.and(ab, bb), Bool.not(ab))
          %b.and_andnot(ab, bb) : {WCon{False{}, Word.zero(p)} == WCon{_, Word.and(p, Word.and(p, at, bt), Word.not(p, at))} : Word(1n+p)}
          %w.and_andnot(p, at, bt) : {WCon{False{}, Word.zero(p)} == WCon{False{}, _} : Word(1n+p)}
          {==}

# (a & b) & ~a == 0 for all 32-bit a, b
def u32.and_andnot(a: U32, b: U32) -> {U32.and(U32.and(a, b), U32.not(a)) == 0 : U32}:
  match a b:
    case U32{x} U32{y}:
      %w.and_andnot(32n, x, y) : {U32{_} == 0 : U32}
      {==}

# Selection
# ---------

def Laws.select_true(x, y):
  match x y:
    case U32{wx} U32{wy}:
      %w.not_ones(32n) : {U32{Word.or(32n, Word.and(32n, wx, Word.ones(32n)), Word.and(32n, wy, _))} == U32{wx} : U32}
      %w.and_zero(32n, wy) : {U32{Word.or(32n, Word.and(32n, wx, Word.ones(32n)), _)} == U32{wx} : U32}
      %w.and_ones(32n, wx) : {U32{Word.or(32n, _, Word.zero(32n))} == U32{wx} : U32}
      %w.or_zero(32n, wx) : {U32{_} == U32{wx} : U32}
      {==}

def Laws.select_false(x, y):
  match x y:
    case U32{wx} U32{wy}:
      %w.not_zero(32n) : {U32{Word.or(32n, Word.and(32n, wx, Word.zero(32n)), Word.and(32n, wy, _))} == U32{wy} : U32}
      %w.and_ones(32n, wy) : {U32{Word.or(32n, Word.and(32n, wx, Word.zero(32n)), _)} == U32{wy} : U32}
      %w.and_zero(32n, wx) : {U32{Word.or(32n, _, wy)} == U32{wy} : U32}
      %w.zero_or(32n, wy) : {U32{_} == U32{wy} : U32}
      {==}

# The make-move state transition
# ------------------------------

def Laws.make_flips_side(p, mv, pc, cap, e):
  match p:
    case B.Pos{side, castle, ep, half, hidx, wk, bk, hlo, hhi, mg, eg, ph, c, mvd, occ}:
      {==}

def Laws.make_counts_ply(p, mv, pc, cap, e):
  match p:
    case B.Pos{side, castle, ep, half, hidx, wk, bk, hlo, hhi, mg, eg, ph, c, mvd, occ}:
      {==}

def Laws.make_records_undo(p, mv, pc, cap, e):
  match p:
    case B.Pos{side, castle, ep, half, hidx, wk, bk, hlo, hhi, mg, eg, ph, c, mvd, occ}:
      ({==}, {==})

def Laws.make_never_adds_rights(p, mv, pc, cap, e):
  match p:
    case B.Pos{side, castle, ep, half, hidx, wk, bk, hlo, hhi, mg, eg, ph, c, mvd, occ}:
      u32.and_andnot(castle, U32.and(C.castle.keep(C.mv.from(mv)), C.castle.keep(C.mv.to(mv))))

def Laws.null_move_state(p):
  match p:
    case B.Pos{side, castle, ep, half, hidx, wk, bk, hlo, hhi, mg, eg, ph, c, mvd, occ}:
      ({==}, ({==}, {==}))
'''


def cases(name, params, domains, leaf, scrut=None):
    out = [f"def Laws.{name}({', '.join(params)}):", f"  match {' '.join(scrut or params)}:"]
    for combo in itertools.product(*domains):
        out.append("    case " + " ".join("Laws." + c + "{}" for c in combo) + ":")
        out.append("      " + leaf)
    return "\n".join(out) + "\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parts = [HEADER, "\n# Exhaustive laws\n# ---------------\n\n"]
    parts.append(cases("square_coordinates", ["f", "r"], [FILES, RANKS], "({==}, ({==}, ({==}, ({==}, {==}))))"))
    parts.append("\n" + cases("step_detection", ["f", "r", "s"], [FILES, RANKS, STEPS], "{==}"))
    parts.append("\n" + cases("direction_table", ["s"], [STEPS], "{==}"))
    parts.append("\n" + cases("side_alternates", ["c"], [COLORS], "({==}, {==})"))
    parts.append("\n" + cases("piece_encoding", ["c", "t"], [COLORS, PTYPES], "({==}, ({==}, {==}))"))
    parts.append("\n" + cases("promotion_metadata", ["f", "g"], [FILES, FLAGS], "{==}"))
    parts.append("\n" + cases("castling_rights_table", ["f", "r"], [FILES, RANKS], "{==}"))
    parts.append("\n" + cases("move_encoding", ["f1", "r1", "f2", "r2", "g"],
                              [FILES, RANKS, FILES, RANKS, FLAGS], "({==}, ({==}, {==}))"))
    path = os.path.join(here, "..", "PROOF.bend")
    open(path, "w").write("".join(parts))
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
