#!/usr/bin/env python3
"""tools/weights.json -> src/weights.bend (evaluation weights as Bend tables)."""
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "weights.json")
feats = json.load(open(src))["features"]
lines = ["# GENERATED by tools/gen_weights.py from tools/weights.json -- do not edit.",
         "# Evaluation weights (centipawns) per feature index; see src/eval.bend.",
         "", "import Base", ""]
for col, name in ((1, "w_mg"), (2, "w_eg")):
    lines += [f"def {name}(i: Nat) -> U32:", "  match i:"]
    for i, f in enumerate(feats):
        lines += [f"    case {i}n:", f"      {int(round(f[col])) & 0xFFFFFFFF}"]
    lines += ["    case _:", "      0", ""]
lines += ["def NFEAT() -> U32:", f"  {len(feats)}", ""]
open(os.path.join(here, "..", "src", "weights.bend"), "w").write("\n".join(lines))
print("wrote src/weights.bend with", len(feats), "features")
